"""Small reference files. Reading a template never changes an experiment."""

FILES = {
    'constraints/pins.tcl': '''# Example lab_top: edit ports/pins using board_info before running.
set_pin_assignment {clk} {LOCATION=R7; IOSTANDARD=LVCMOS33;}
set_pin_assignment {rst_n} {LOCATION=A9; IOSTANDARD=LVCMOS33;}
set_pin_assignment {led} {LOCATION=B14; IOSTANDARD=LVCMOS33;}
''',
    'constraints/clock.sdc': '''create_clock -name clk -period 20 [get_ports {clk}]
''',
    'scripts/functional.do': '''vlib work
vlog -sv -work work {*}$rtl_files {*}$tb_files
vsim -t 1ps -onfinish exit work.tb
run -all
''',
    'scripts/implement.tcl': '''import_device eagle_s20.db -package BG256
read_verilog -file $rtl_files -top $design_top
source source/constraints/pins.tcl
optimize_rtl
read_sdc source/constraints/clock.sdc
optimize_gate
place
route
report_clock_summary -file clock_summary.rpt
report_timing -file timing.rpt -sdf route.sdf
write_verilog post_route.v -back
bitgen -bit design.bit
''',
    'scripts/post_route.do': '''vlib work
vlib rtl_reference
vlog -sv -work rtl_reference {*}$rtl_files
vlog -work work {*}$td_models
vlog -work work post_route.v
vlog -sv -work work {*}$tb_files
vsim -t 1ps -onfinish exit -L work -L rtl_reference -sdfmax /tb/dut=route.sdf work.tb work.glbl
run -all
''',
}


def templates(path=None):
    if path is not None and path not in FILES:
        raise ValueError('未知模板路径')
    return {'files': {path: FILES[path]} if path else dict(FILES),
            'guide': 'Reference only: use write_file to save/adapt each file. No RTL/TB is generated by templates. '
                     'Runner variables: rtl_files, tb_files (snapshot paths), td_models (EG4 vendor models), design_top. '
                     'Paths are relative to the run directory, source/... for editable files. '
                     'TD outputs: design.bit, post_route.v, route.sdf, timing.rpt, clock_summary.rpt. '
                     'Tcl supports variables, loops, procedures, conditions and source within source/. '
                     'Use run_tool to execute your saved script; read_run for paged logs/commands/reports. '
                     'Native OpenCode read/grep/glob may also inspect the original logs directly; native write/edit may modify source files. '
                     'ModelSim diagnostic options: -quiet, +acc, -voptargs=+acc, +nowarnTFMPC, -suppress 2685,2718,2182,8756 for unused port warnings. '
                     'Do not suppress assertion, timing or SDF failures. ModelSim help can be queried with vsim -help. '
                     'Functional and post-route use the same tb/dut and actual HDL assertions. '
                     'Post-route: RTL helpers in rtl_reference, vendor/netlist/TB in work, work library first. '
                     'No shell, DLL loading, network or board programming in scripts. '
                     'Available command list is returned by run_tool on rejection; help is available in query runs.'}
